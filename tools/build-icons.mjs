// Extracts the Lucide (ISC) UI icons and Simple Icons (CC0) brand glyphs used by index.html
// into a compact JS object. Output: tools/icons.generated.js — paste it over the
// `/* ICONS:BEGIN */ … /* ICONS:END */` block in index.html (npm run icons does this automatically).
import fs from "node:fs";
import path from "node:path";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const L = (n) => path.join(ROOT, "node_modules/lucide-static/icons", n + ".svg");
const S = (n) => path.join(ROOT, "node_modules/simple-icons/icons", n + ".svg");
export const LUCIDE = `search x menu phone mail sun moon monitor settings-2 chevron-down chevron-left chevron-right arrow-right arrow-left plus
minus trash-2 copy check download file-text printer zoom-in zoom-out book-open map-pin clock building-2 house store
coffee briefcase graduation-cap hotel factory shield-check wifi siren fingerprint door-open monitor-play phone-call
receipt list layout-grid sliders-horizontal columns-3 link info circle-check award headset wrench handshake lightbulb
gauge moon-star scan-eye laptop zap users layers radio volume-2 server router smartphone tv timer lock bell-ring
clipboard-check hard-hat tag cable activity badge-check id-card blinds plug audio-lines presentation split
arrow-up-right circle-help map image rows-3 workflow`.split(/\s+/);
const out = {};
for (const n of LUCIDE) {
  const svg = fs.readFileSync(L(n), "utf8");
  out[n] = svg.replace(/<!--.*?-->/s, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, "").replace(/ \/>/g, "/>").trim();
}
const brands = {};
for (const n of ["whatsapp", "facebook", "instagram", "tiktok"]) {
  brands[n] = fs.readFileSync(S(n), "utf8").match(/ d="([^"]+)"/)[1];
}
const js = `/* ICONS:BEGIN — generated by tools/build-icons.mjs (Lucide ISC, Simple Icons CC0) */\nconst LUCIDE = ${JSON.stringify(out)};\nconst BRAND_GLYPHS = ${JSON.stringify(brands)};\n/* ICONS:END */`;
fs.writeFileSync(path.join(ROOT, "tools/icons.generated.js"), js);
const idx = path.join(ROOT, "index.html");
if (fs.existsSync(idx)) {
  const html = fs.readFileSync(idx, "utf8");
  if (html.includes("/* ICONS:BEGIN")) fs.writeFileSync(idx, html.replace(/\/\* ICONS:BEGIN[\s\S]*?\/\* ICONS:END \*\//, () => js));
}
console.log(Object.keys(out).length, "lucide icons,", js.length, "bytes");
